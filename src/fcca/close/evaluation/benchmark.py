"""Multi-provider benchmark runner.

The rule this module exists to enforce: **a number is written only if it was
produced by a run that actually happened.** If a provider's optional dependency
is absent, or credentials are not configured, or the client cannot be
constructed, the run is recorded with status ``not_run`` and every metric cell in
the CSV reads ``not_run``. There is no default, no placeholder and no estimate.

That is what makes the comparison artefact worth showing: the same table can be
regenerated by anyone with their own AWS or Google Cloud account, and the empty
cells say plainly that nobody has done so yet.
"""

from __future__ import annotations

import csv
import json
import logging
import re
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

from fcca.close.evaluation.metrics import BenchmarkMetrics, CaseEvaluation, evaluate_cases
from fcca.close.models import CaseFailure, CaseResult, LabelledCase
from fcca.close.workflow.control_agent import ControlAgent
from fcca.shared.config import ProviderName, Settings, get_settings
from fcca.shared.errors import FCCAError
from fcca.shared.providers.base import describe_provider

logger = logging.getLogger(__name__)

RunStatus = Literal["ok", "not_run", "error"]

NOT_RUN = "not_run"

CSV_COLUMNS = [
    "provider",
    "model",
    "status",
    "note",
    "n_cases",
    "risk_accuracy",
    "action_category_accuracy",
    "escalation_precision",
    "escalation_recall",
    "escalation_f1",
    "retrieval_recall",
    "citation_accuracy",
    "structured_output_success",
    "ungrounded_citation_rate",
    "unsupported_recommendation_rate",
    "auto_recommendation_rate",
    "median_latency_ms",
    "p95_latency_ms",
    "cost_per_case_usd",
    "run_at",
]


@dataclass
class BenchmarkRun:
    """One provider's result, including the case where it never ran."""

    provider: str
    model: str
    status: RunStatus
    note: str = ""
    metrics: BenchmarkMetrics | None = None
    evaluations: list[CaseEvaluation] = field(default_factory=list)
    run_at: str = ""

    def as_row(self) -> dict[str, object]:
        if self.metrics is None:
            return {
                "provider": self.provider,
                "model": self.model,
                "status": self.status,
                "note": self.note,
                **{
                    column: NOT_RUN
                    for column in CSV_COLUMNS
                    if column not in {"provider", "model", "status", "note", "run_at"}
                },
                "run_at": self.run_at or NOT_RUN,
            }
        metrics = self.metrics
        return {
            "provider": self.provider,
            "model": self.model,
            "status": self.status,
            "note": self.note,
            "n_cases": metrics.n_cases,
            "risk_accuracy": metrics.risk_accuracy,
            "action_category_accuracy": metrics.action_category_accuracy,
            "escalation_precision": metrics.escalation_precision,
            "escalation_recall": metrics.escalation_recall,
            "escalation_f1": metrics.escalation_f1,
            "retrieval_recall": metrics.retrieval_recall,
            "citation_accuracy": metrics.citation_accuracy,
            "structured_output_success": metrics.structured_output_success,
            "ungrounded_citation_rate": metrics.ungrounded_citation_rate,
            "unsupported_recommendation_rate": metrics.unsupported_recommendation_rate,
            "auto_recommendation_rate": metrics.auto_recommendation_rate,
            "median_latency_ms": metrics.median_latency_ms,
            "p95_latency_ms": metrics.p95_latency_ms,
            "cost_per_case_usd": (
                metrics.cost_per_case_usd if metrics.cost_per_case_usd is not None else NOT_RUN
            ),
            "run_at": self.run_at,
        }


def load_labels(settings: Settings | None = None) -> dict[str, LabelledCase]:
    """Load the labelled evaluation set."""
    settings = settings or get_settings()
    path = settings.labelled_set_path
    if not path.exists():
        raise FCCAError(f"labelled set not found at {path}. Run `fcca generate-data` first.")
    raw = json.loads(path.read_text(encoding="utf-8"))
    labels = [LabelledCase.model_validate(item) for item in raw]
    return {label.exception_id: label for label in labels}


def run_benchmark(
    provider: ProviderName,
    limit: int | None = None,
    settings: Settings | None = None,
    with_audit: bool = True,
    on_case: Callable[[str, int, int], None] | None = None,
) -> BenchmarkRun:
    """Evaluate one provider over the labelled set.

    Never raises for an unavailable provider: that is reported as ``not_run``.
    """
    settings = settings or get_settings()
    spec = describe_provider(provider, settings=settings)
    labels = load_labels(settings)
    exception_ids = list(labels)[: limit or len(labels)]

    if not spec.installed:
        return BenchmarkRun(
            provider=spec.provider,
            model=spec.model,
            status="not_run",
            note=(
                f"optional dependency for '{spec.provider}' is not installed; "
                f'install with pip install "finance-close-control-agent[{spec.provider}]"'
            ),
        )

    try:
        agent = ControlAgent.build(provider=provider, settings=settings, with_audit=with_audit)
    except FCCAError as exc:
        # Missing or misconfigured credentials land here. Not an error in the
        # benchmark; simply a provider nobody has run yet.
        return BenchmarkRun(
            provider=spec.provider,
            model=spec.model,
            status="not_run",
            note=f"client could not be constructed: {exc}",
        )

    results: list[CaseResult | CaseFailure] = []
    try:
        for index, exception_id in enumerate(exception_ids, start=1):
            if on_case is not None:
                on_case(exception_id, index, len(exception_ids))
            results.append(agent.run_safe(exception_id))
    finally:
        agent.close()

    metrics, evaluations = evaluate_cases(results, labels)
    note = ""
    if provider == "mock":
        note = "deterministic stub; measures pipeline integrity, not model quality"
    return BenchmarkRun(
        provider=spec.provider,
        model=spec.model,
        status="ok",
        note=note,
        metrics=metrics,
        evaluations=evaluations,
        run_at=datetime.now(UTC).isoformat(timespec="seconds"),
    )


def write_benchmark_csv(runs: list[BenchmarkRun], path: Path) -> Path:
    """Write the provider comparison table."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        for run in runs:
            writer.writerow(run.as_row())
    return path


def write_run_detail(run: BenchmarkRun, path: Path) -> Path:
    """Write per-case detail for one run, for error analysis."""
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "provider": run.provider,
        "model": run.model,
        "status": run.status,
        "note": run.note,
        "run_at": run.run_at,
        "metrics": run.metrics.model_dump() if run.metrics else None,
        "cases": [
            {
                "exception_id": e.exception_id,
                "scenario": e.scenario,
                "decided": e.decided,
                "expected_risk": e.expected_risk,
                "actual_risk": e.actual_risk,
                "risk_correct": e.risk_correct,
                "expected_review": e.expected_review,
                "actual_review": e.actual_review,
                "expected_action": e.expected_action,
                "actual_action": e.actual_action,
                "expected_document": e.expected_document,
                "retrieved_expected_document": e.retrieved_expected_document,
                "cited_expected_document": e.cited_expected_document,
                "grounded_citations": e.grounded_citations,
                "ungrounded_citations": e.ungrounded_citations,
                "latency_ms": e.latency_ms,
                "error": e.error,
            }
            for e in run.evaluations
        ],
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def run_slug(provider: str, model: str) -> str:
    """Filename key for one recorded run.

    Keyed on provider *and* model, because "changing BEDROCK_MODEL_ID changes no
    code" is a claim this repository makes, and a comparison table that keeps
    one row per provider quietly overwrites the evidence for it every time a
    second model is tried.
    """
    safe = re.sub(r"[^a-z0-9]+", "-", model.lower()).strip("-")
    return f"eval_{provider}__{safe}"


def load_run_detail(path: Path) -> BenchmarkRun | None:
    """Read a previously written per-provider run, if it exists.

    Used so that ``benchmark.csv`` can be rebuilt from every run recorded so far
    — including a Bedrock or Vertex run performed on a different machine with its
    own credentials — instead of a single-provider run silently discarding them.
    """
    if not path.exists():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        metrics = payload.get("metrics")
        return BenchmarkRun(
            provider=payload["provider"],
            model=payload["model"],
            status=payload.get("status", "ok"),
            note=payload.get("note", ""),
            metrics=BenchmarkMetrics.model_validate(metrics) if metrics else None,
            run_at=payload.get("run_at", ""),
        )
    except (json.JSONDecodeError, KeyError, ValueError) as exc:  # pragma: no cover - defensive
        logger.warning("could not read previous run detail at %s: %s", path, exc)
        return None


def _all_recorded(settings: Settings, key: tuple[str, str]) -> list[BenchmarkRun]:
    """Every recorded pass for one provider and model, repeats included."""
    runs = []
    for path in sorted(settings.results_dir.glob("eval_*.json")):
        run = load_run_detail(path)
        if run is not None and (run.provider, run.model) == key:
            runs.append(run)
    return runs


def collect_runs(fresh: list[BenchmarkRun], settings: Settings | None = None) -> list[BenchmarkRun]:
    """Combine this invocation's runs with every run recorded previously.

    One row per provider *and model*, so a second model on the same provider
    adds a comparison rather than replacing the first. Providers with no
    recorded run at all still appear once, as ``not_run``.
    """
    settings = settings or get_settings()
    fresh_keys = {(run.provider, run.model) for run in fresh if run.metrics is not None}

    collected: list[BenchmarkRun] = [run for run in fresh if run.metrics is not None]

    # Repeat passes of the same model are kept on disk — measuring how much a
    # single run moves is the point of running twice — but the comparison table
    # holds one row per provider and model, showing the most recent. Otherwise
    # a repeat reads as two different configurations.
    seen: set[tuple[str, str]] = set(fresh_keys)
    for path in sorted(settings.results_dir.glob("eval_*.json")):
        previous = load_run_detail(path)
        if previous is None:
            continue
        key = (previous.provider, previous.model)
        if key in seen:
            continue
        newest = max(
            (r for r in _all_recorded(settings, key) if r is not None),
            key=lambda r: r.run_at or "",
        )
        seen.add(key)
        collected.append(newest)

    for provider in ("mock", "bedrock", "vertex"):
        if any(run.provider == provider for run in collected):
            continue
        unrun = next((run for run in fresh if run.provider == provider), None)
        if unrun is not None:
            collected.append(unrun)
            continue
        spec = describe_provider(provider, settings=settings)  # type: ignore[arg-type]
        collected.append(
            BenchmarkRun(
                provider=provider,
                model=spec.model,
                status="not_run",
                note="not evaluated in this repository; requires the provider's credentials",
            )
        )

    order = {"mock": 0, "bedrock": 1, "vertex": 2}
    collected.sort(key=lambda run: (order.get(run.provider, 9), run.model))
    return collected
